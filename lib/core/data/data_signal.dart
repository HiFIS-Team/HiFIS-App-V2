/// 화면끼리 **'방금 바뀌었다'** 고 알려 주는 자리
///
/// ## 왜 필요한가
///
/// 탭은 [ScreenRefresh] 로 다시 받는데, 거기에는 **1분 간격**이 있다
/// (`screenRefreshGap` — macOS 가 창 포커스만 잃어도 오가는 것을 막으려고 둔 것).
/// 그 사이에 다른 화면에서 값이 바뀌면 **낡은 줄이 그대로 보인다.**
///
/// 결재가 제일 아프다. 홈 결재함에서 승인하고 1분 안에 급여 탭으로 가면
/// 이미 처리한 건이 대기로 남아 있고, **다시 누르면 400 이 난다.**
///
/// 이 신호를 지켜보는 화면은 **간격을 안 따지고** 다시 받는다.
///
/// ## 쓰는 법
///
/// 화면은 [ScreenRefresh] 의 `watchSignals` 에 적기만 하면 된다 —
/// 붙이고 떼는 것은 믹스인이 한다.
///
/// ```dart
/// @override
/// List<ValueNotifier<int>> get watchSignals => [approvalChanged];
/// ```
///
/// 쏘는 쪽은 **API 계층이다** (`lib/core/api/`). 화면에서 쏘면 부르는 자리가
/// 늘어날 때마다 빠뜨린다 — 결재를 바꾸는 메서드가 지금도 열일곱이다.
///
/// ## 값에는 뜻이 없다
///
/// 몇 번 바뀌었는지는 아무도 안 본다. **바뀌었다는 것만** 알린다.
library;

import 'package:flutter/foundation.dart';

/// 출퇴근이 방금 찍혔다
///
/// 출퇴근은 **카운터 PC 의 스캐너**가 찍는다. 앱은 그 사실을 모르므로
/// 바코드를 띄운 화면이 서버에 물어보고 알아낸다. 그때 홈의 '오늘 근무'
/// 카드도 같이 바뀌어야 하는데, 서로 남남이라 알려 줄 길이 없었다
/// (찍고 홈으로 와도 한동안 '미출근' 그대로였다).
final attendanceChanged = ValueNotifier<int>(0);

void notifyAttendanceChanged() => attendanceChanged.value++;

/// 결재가 방금 바뀌었다 — **여섯 갈래가 한 신호다**
///
/// 급여 · 월차 · 일정 · 프로젝트 기한 · 전자결재 · 내 업무.
/// 갈래마다 신호를 나누지 않는 이유는 **보는 화면이 갈래를 안 가리기 때문**이다 —
/// 홈 결재함 한 칸에 여섯이 같이 서고([InboxKind]), 결재 전체보기도 하나다.
/// 나누면 화면마다 여섯 개를 다 적어야 하고 하나 빠뜨리면 그 갈래만 안 도는데,
/// 그건 눈에 안 띈다.
///
/// **신청·취소도 여기 든다.** 결재함에 줄이 새로 서거나 빠지는 것이라
/// 승인·반려와 같은 값이다.
final approvalChanged = ValueNotifier<int>(0);

void notifyApprovalChanged() => approvalChanged.value++;

/// 세션 싸인이 방금 찍혔다
///
/// 싸인 한 건이 **PT 커미션**(급여)과 **수업왕 점수**를 같이 올린다. 그런데
/// 급여 화면은 다른 탭이라 [ScreenRefresh] 의 1분 간격에 걸려서, 찍고 바로
/// 넘어가면 **옛 금액이 그대로 떠 있었다** (2026-08-31 대표 요청).
///
/// 급여의 PT 커미션은 미리 저장해 둔 값이 아니라 `GET /payslips/me/accrued`
/// 가 **부를 때마다 그 주기 싸인을 다시 세는** 값이라, 다시 받기만 하면 맞는다.
final sessionSignChanged = ValueNotifier<int>(0);

void notifySessionSignChanged() => sessionSignChanged.value++;

/// 회원 명단이 방금 바뀌었다 — **등록 · 수정 · 삭제**
///
/// 회원을 지우는 자리(회원 정보 화면)와 재등록 목록이 **서로 남남이다.**
/// 재등록 탭은 `_LessonStore` 가 들고 있는 명단을 읽는데, 그 저장소는 수업
/// 화면이 만들어질 때만 받아 온다 — 지우고 바로 등록하러 가면 **없는 회원이
/// 목록에 그대로 서 있었다** (2026-09-01 화순 점장이 겪었다. 서버에서는
/// 지워졌는데 앱만 옛 값을 들고 있었다).
///
/// **셋을 한 신호로 둔다.** 이름을 고치는 것도 목록에 찍히는 값이 바뀌는
/// 일이라 다시 받아야 하고, 갈래를 나누면 화면마다 셋을 다 적게 된다.
final memberChanged = ValueNotifier<int>(0);

void notifyMemberChanged() => memberChanged.value++;
